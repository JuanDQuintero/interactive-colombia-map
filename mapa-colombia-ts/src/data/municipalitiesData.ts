/**
 * Get all municipalities for a specific department
 */
export const getMunicipalitiesForDepartment = (departmentId: string): MunicipalityData[] => {
    return municipalitiesByDepartment[departmentId] || [];
};

/**
 * Default municipality for each department. This keeps the UX focused on the main city
 * when a department modal opens, while still allowing a user to switch to other towns.
 */
export const getDefaultMunicipalityForDepartment = (departmentId: string): string => {
    return getMunicipalitiesForDepartment(departmentId)[0]?.id ?? 'all';
};

/**
 * Get a specific municipality by its ID
 */
export const getMunicipalityById = (municipalityId: string): MunicipalityData | undefined => {
    for (const municipalities of Object.values(municipalitiesByDepartment)) {
        const municipality = municipalities.find(m => m.id === municipalityId);
        if (municipality) return municipality;
    }
    return undefined;
};
